void gui_init(uint64_t fb_addr, uint32_t width, uint32_t height, uint32_t pitch, uint32_t bpp) {
    (void)bpp;
    fb = (uint32_t*)(uintptr_t)fb_addr;
    fb_width = width;
    fb_height = height;
    fb_pitch = pitch / 4;
}

void gui_draw_rect(int x, int y, int w, int h, uint32_t color) {
    if (!fb) return;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > (int)fb_width) w = fb_width - x;
    if (y + h > (int)fb_height) h = fb_height - y;
    for (int yy = 0; yy < h; yy++) {
        uint32_t* row = fb + (y + yy) * fb_pitch + x;
        for (int xx = 0; xx < w; xx++) {
            row[xx] = color;
        }
    }
}

void gui_draw_text(int x, int y, const char* text, uint32_t color) {
    int cx = x;
    int cy = y;
    for (size_t i = 0; text[i]; i++) {
        unsigned char c = (unsigned char)text[i];
        if (c == '\n') {
            cx = x;
            cy += 10;
            continue;
        }
        if (c > 127) {
            continue;
        }
        for (int row = 0; row < 8; row++) {
            uint8_t bits = font8x8[(int)c][row];
            for (int col = 0; col < 8; col++) {
                if (bits & (1 << col)) {
                    int px = cx + col;
                    int py = cy + row;
                    if (px >= 0 && py >= 0 && px < (int)fb_width && py < (int)fb_height) {
                        fb[py * fb_pitch + px] = color;
                    }
                }
            }
        }
        cx += 8;
    }
}

void gui_draw_window(int x, int y, int w, int h, const char* title) {
    gui_draw_rect(x, y, w, h, 0xFF1E1E1E);
    gui_draw_rect(x, y, w, 20, 0xFF3A6EA5);
    gui_draw_text(x + 6, y + 6, title, 0xFFFFFFFF);
}

void gui_draw_cursor(mouse_state_t mouse) {
    gui_draw_rect(mouse.x, mouse.y, 6, 10, 0xFFFFFFFF);
}

void gui_tick(void) {
    (void)fb;
}
